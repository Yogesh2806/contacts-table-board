// Generates src/data.ts from the repo's single sources of truth:
//   design/tokens.json  (colours, space, radius, type, shadows, layout)
//   src/data/contacts.ts (the ten fictional contacts, owners, current user)
//   ionicons (the glyphs src/components/ui/Icon.tsx bundles, plus the sidebar glyph from Sidebar.tsx)
// Run:  npm run gen-data
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));

// ---- contacts: evaluate the TS array literal (it is plain data) ----
const ts = readFileSync(join(root, 'src/data/contacts.ts'), 'utf8');
const arr = ts.slice(ts.indexOf('INITIAL_CONTACTS: Contact[] = ') + 'INITIAL_CONTACTS: Contact[] = '.length);
const contacts = new Function('return ' + arr.slice(0, arr.indexOf('\n]') + 2))();
const owners = new Function('return ' + ts.match(/OWNERS = (\[[^\]]*\])/)[1])();
const me = new Function('return ' + ts.match(/CURRENT_USER = (\{[^}]*\})/)[1])();

// ---- icons: the exact list Icon.tsx bundles ----
const iconSrc = readFileSync(join(root, 'src/components/ui/Icon.tsx'), 'utf8');
const names = iconSrc.match(/svg\/\{([^}]+)\}\.svg/)[1].split(',');
const ionDirs = [join(root, 'node_modules/ionicons/dist/svg'), join(here, '..', 'node_modules/ionicons/dist/svg')];
const ionDir = ionDirs.find((d) => existsSync(d));
if (!ionDir) throw new Error('ionicons is not installed. Run `npm install` in figma-plugin/ first.');
const icons = {};
for (const n of names) {
  let svg = readFileSync(join(ionDir, n + '.svg'), 'utf8')
    .replace(/<title>.*?<\/title>/g, '')
    .replace(/ xmlns="[^"]*"/, '')
    .replace(/ class="[^"]*"/, '')
    .replace(/currentColor/g, '#000000')
    .replace(/\s+/g, ' ')
    .trim();
  if (!/<svg[^>]* fill=/.test(svg)) svg = svg.replace('<svg ', '<svg fill="#000000" ');
  icons[n] = svg;
}
// The sidebar toggle glyph is drawn inline in Sidebar.tsx.
icons['sidebar'] = '<svg viewBox="0 0 16 16" fill="none" stroke="#000000" stroke-width="1.5"><rect x="1.75" y="2.75" width="12.5" height="10.5" rx="2"/><path d="M6 3v10"/></svg>';

// ---- colours ----
const hues = tokens.color.hue; // blue/violet/amber/green -> step -> {light,dark}
const prim = { light: [], dark: [] }; // [name, hex]
for (const mode of ['light', 'dark']) {
  for (const [n, hex] of Object.entries(tokens.color.neutral)) {
    // neutral values are light-mode greys; the dark primitives hold the same ramp (semantic aliases pick the other end)
    prim[mode].push(['neutral/' + n, hex]);
  }
  for (const [h, steps] of Object.entries(hues)) for (const [s, v] of Object.entries(steps)) prim[mode].push([`${h}/${s}`, v[mode]]);
}
const semantic = Object.entries(tokens.color.semantic).map(([name, v]) => ({ name, light: v.light, dark: v.dark, alias: v.alias || null }));

const DATA = {
  font: tokens.font,
  prim,
  semantic,
  stage: tokens.stage,
  space: Object.entries(tokens.space).map(([k, v]) => [k, v]),
  radius: Object.entries(tokens.radius).map(([k, v]) => [k, v]),
  type: Object.entries(tokens.type).map(([k, v]) => ({ name: k, ...v })),
  shadow: Object.entries(tokens.shadow).map(([k, v]) => ({ name: k, light: v.light, dark: v.dark })),
  layout: tokens.layout,
  motion: tokens.motion,
  contacts,
  owners,
  me,
  icons,
};
writeFileSync(join(here, '..', 'src/data.ts'), '// GENERATED by scripts/gen-data.mjs from design/tokens.json, src/data/contacts.ts and ionicons. Do not edit.\n/* eslint-disable */\nexport const DATA: any = ' + JSON.stringify(DATA) + ';\n');
console.log(`data.ts: ${semantic.length} semantic, ${prim.light.length} primitives/mode, ${Object.keys(icons).length} icons, ${contacts.length} contacts`);
